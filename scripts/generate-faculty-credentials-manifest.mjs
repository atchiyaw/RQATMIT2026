/**
 * Walks `Faculty Credentials/` and emits `src/generated/facultyCredentialsManifest.ts`.
 * Run: node scripts/generate-faculty-credentials-manifest.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const credentialsRoot = path.join(projectRoot, 'Faculty Credentials');
const outFile = path.join(projectRoot, 'src', 'generated', 'facultyCredentialsManifest.ts');

/** Slide 6 faculty names — warn if folder missing on disk */
const EXPECTED_FACULTY_FOLDERS = [
  'ABIO, Arjay Formalejo',
  'ARTIAGA, Rowell John Baterna',
  'ATOLE, Ronnel Rimando',
  'BELLO, Leo Constantine S.',
  'BRIONES, Salvador II V.',
  'BRIONES, Shane C.',
  'CAPUCAO, Joni Neil Borja',
  'CUYA, Kennedy Centeno',
  'INDICO, Michael H',
  'PAGA, Jonathan',
  'PESINO, Hazel Jean C.',
];

function walkDir(dirPath, relPrefix) {
  let entries = [];
  try {
    entries = fs.readdirSync(dirPath, {withFileTypes: true});
  } catch {
    return [];
  }
  entries.sort((a, b) => {
    if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
    return a.name.localeCompare(b.name);
  });

  const children = [];
  for (const ent of entries) {
    if (ent.name.startsWith('.')) continue;
    const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name;
    const full = path.join(dirPath, ent.name);
    if (ent.isDirectory()) {
      children.push({
        type: 'dir',
        name: ent.name,
        children: walkDir(full, rel),
      });
    } else {
      children.push({
        type: 'file',
        name: ent.name,
        relPath: rel.replace(/\\/g, '/'),
      });
    }
  }
  return children;
}

function countFiles(nodes) {
  let n = 0;
  for (const c of nodes) {
    if (c.type === 'file') n += 1;
    else n += countFiles(c.children);
  }
  return n;
}

function main() {
  if (!fs.existsSync(credentialsRoot)) {
    console.warn('[generate-faculty-credentials-manifest] Faculty Credentials/ not found; writing empty manifest.');
    fs.mkdirSync(path.dirname(outFile), {recursive: true});
    fs.writeFileSync(
      outFile,
      `// Auto-generated — run: npm run generate:credentials
export type CredentialFileNode = { type: 'file'; name: string; relPath: string };
export type CredentialDirNode = { type: 'dir'; name: string; children: CredentialNode[] };
export type CredentialNode = CredentialFileNode | CredentialDirNode;
export type CredentialTreeRoot = { children: CredentialNode[] };

export const facultyCredentialsFileCounts: Record<string, number> = {};
export const facultyCredentialsManifest: Record<string, CredentialTreeRoot> = {};
`,
      'utf8',
    );
    return;
  }

  const manifest = {};
  const fileCounts = {};

  const top = fs.readdirSync(credentialsRoot, {withFileTypes: true});
  for (const ent of top) {
    if (!ent.isDirectory() || ent.name.startsWith('.')) continue;
    const facultyName = ent.name;
    const children = walkDir(path.join(credentialsRoot, facultyName), '');
    manifest[facultyName] = {children};
    fileCounts[facultyName] = countFiles(children);
  }

  for (const exp of EXPECTED_FACULTY_FOLDERS) {
    if (manifest[exp] == null) {
      console.warn(`[generate-faculty-credentials] No folder on disk for: "${exp}"`);
    }
  }

  fs.mkdirSync(path.dirname(outFile), {recursive: true});
  const jsonManifest = JSON.stringify(manifest);
  const jsonCounts = JSON.stringify(fileCounts);

  const ts = `// Auto-generated by scripts/generate-faculty-credentials-manifest.mjs — run: npm run generate:credentials

export type CredentialFileNode = { type: 'file'; name: string; relPath: string };
export type CredentialDirNode = { type: 'dir'; name: string; children: CredentialNode[] };
export type CredentialNode = CredentialFileNode | CredentialDirNode;
/** Root of one faculty folder (children = top-level entries). */
export type CredentialTreeRoot = { children: CredentialNode[] };

export const facultyCredentialsFileCounts: Record<string, number> = ${jsonCounts};

export const facultyCredentialsManifest: Record<string, CredentialTreeRoot> = ${jsonManifest};
`;

  fs.writeFileSync(outFile, ts, 'utf8');
  console.log(`[generate-faculty-credentials-manifest] Wrote ${outFile} (${Object.keys(manifest).length} faculty folders).`);
}

main();
