/**
 * Reads `Faculty Photo/` and emits `src/generated/facultyPhotos.ts`.
 * Filename (without extension, trimmed) must match `facultyList[].name` in presentationData.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const photoDir = path.join(projectRoot, 'Faculty Photo');
const outFile = path.join(projectRoot, 'src', 'generated', 'facultyPhotos.ts');

const EXPECTED_NAMES = [
  'ABIO, Arjay Formalejo',
  'ARTIAGA, Rowell John Baterna',
  'ATOLE, Ronnel Rimando',
  'BELLO, Leo Constantine S.',
  'BRIONES, Salvador II V.',
  'BRIONES, Shane C.',
  'CAPUCAO, Joni Neil Borja',
  'CUYA, Kennedy Centeno',
  'INDICO, Michael H',
  'PAGA, Jonathan',
  'PESINO, Hazel Jean C.',
];

function photoUrl(filename) {
  return `/faculty-photos/${encodeURIComponent(filename)}`;
}

function main() {
  const map = {};

  if (!fs.existsSync(photoDir)) {
    console.warn('[generate-faculty-photo-manifest] Faculty Photo/ not found.');
    fs.mkdirSync(path.dirname(outFile), {recursive: true});
    fs.writeFileSync(
      outFile,
      `// Auto-generated — run: npm run generate:photos
export const FACULTY_PHOTO_URLS: Record<string, string> = {};
export const KENNEDY_CUYA_FACULTY_PHOTO_URL = '';
`,
      'utf8',
    );
    return;
  }

  const files = fs.readdirSync(photoDir).filter((f) => /\.(png|jpe?g|gif|webp)$/i.test(f));
  for (const f of files) {
    const key = path.parse(f).name.trim();
    map[key] = photoUrl(f);
  }

  for (const exp of EXPECTED_NAMES) {
    if (map[exp] == null) {
      console.warn(`[generate-faculty-photo-manifest] No photo file matching name: "${exp}"`);
    }
  }

  const kennedyUrl = map['CUYA, Kennedy Centeno'] ?? '';

  fs.mkdirSync(path.dirname(outFile), {recursive: true});
  const json = JSON.stringify(map, null, 2);
  const ts = `// Auto-generated by scripts/generate-faculty-photo-manifest.mjs — run: npm run generate:photos

/** Faculty list \`name\` → URL under \`/faculty-photos/\` */
export const FACULTY_PHOTO_URLS: Record<string, string> = ${json};

/** Same as FACULTY_PHOTO_URLS["CUYA, Kennedy Centeno"] — Graduate Program Coordinator photo */
export const KENNEDY_CUYA_FACULTY_PHOTO_URL = ${JSON.stringify(kennedyUrl)};
`;

  fs.writeFileSync(outFile, ts, 'utf8');
  console.log(`[generate-faculty-photo-manifest] Wrote ${outFile} (${Object.keys(map).length} photos).`);
}

main();
