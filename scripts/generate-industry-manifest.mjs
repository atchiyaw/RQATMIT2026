/**
 * Walks `Industry/` and emits `src/generated/industryManifest.ts`.
 * Run: node scripts/generate-industry-manifest.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const industryRoot = path.join(projectRoot, 'Industry');
const outFile = path.join(projectRoot, 'src', 'generated', 'industryManifest.ts');

function walkDir(dirPath, relPrefix) {
  let entries = [];
  try {
    entries = fs.readdirSync(dirPath, {withFileTypes: true});
  } catch {
    return [];
  }

  entries.sort((a, b) => {
    if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
    return a.name.localeCompare(b.name);
  });

  const children = [];
  for (const ent of entries) {
    if (ent.name.startsWith('.')) continue;
    const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name;
    const full = path.join(dirPath, ent.name);

    if (ent.isDirectory()) {
      children.push({
        type: 'dir',
        name: ent.name,
        children: walkDir(full, rel),
      });
    } else {
      children.push({
        type: 'file',
        name: ent.name,
        relPath: rel.replace(/\\/g, '/'),
      });
    }
  }

  return children;
}

function main() {
  if (!fs.existsSync(industryRoot)) {
    console.warn('[generate-industry-manifest] Industry/ not found; writing empty tree.');
    fs.mkdirSync(path.dirname(outFile), {recursive: true});
    fs.writeFileSync(
      outFile,
      `// Auto-generated — run: npm run generate:industry
export type IndustryFileNode = { type: 'file'; name: string; relPath: string };
export type IndustryDirNode = { type: 'dir'; name: string; children: IndustryNode[] };
export type IndustryNode = IndustryFileNode | IndustryDirNode;
export type IndustryDocumentTree = { children: IndustryNode[] };
export const industryDocumentTree: IndustryDocumentTree = { children: [] };
`,
      'utf8',
    );
    return;
  }

  const children = walkDir(industryRoot, '');
  const json = JSON.stringify({children}, null, 2);

  fs.mkdirSync(path.dirname(outFile), {recursive: true});
  const ts = `// Auto-generated by scripts/generate-industry-manifest.mjs — run: npm run generate:industry

export type IndustryFileNode = { type: 'file'; name: string; relPath: string };
export type IndustryDirNode = { type: 'dir'; name: string; children: IndustryNode[] };
export type IndustryNode = IndustryFileNode | IndustryDirNode;
export type IndustryDocumentTree = { children: IndustryNode[] };

export const industryDocumentTree: IndustryDocumentTree = ${json};
`;

  fs.writeFileSync(outFile, ts, 'utf8');
  console.log(`[generate-industry-manifest] Wrote ${outFile} (${children.length} top-level entries).`);
}

main();

