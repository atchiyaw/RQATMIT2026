/**
 * Walks `GPMO/` and emits `src/generated/gpmoManifest.ts`.
 * Run: node scripts/generate-gpmo-manifest.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const gpmoRoot = path.join(projectRoot, 'GPMO');
const outFile = path.join(projectRoot, 'src', 'generated', 'gpmoManifest.ts');

function walkDir(dirPath, relPrefix) {
  let entries = [];
  try {
    entries = fs.readdirSync(dirPath, {withFileTypes: true});
  } catch {
    return [];
  }
  entries.sort((a, b) => {
    if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
    return a.name.localeCompare(b.name);
  });

  const children = [];
  for (const ent of entries) {
    if (ent.name.startsWith('.')) continue;
    const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name;
    const full = path.join(dirPath, ent.name);
    if (ent.isDirectory()) {
      children.push({
        type: 'dir',
        name: ent.name,
        children: walkDir(full, rel),
      });
    } else {
      children.push({
        type: 'file',
        name: ent.name,
        relPath: rel.replace(/\\/g, '/'),
      });
    }
  }
  return children;
}

function main() {
  if (!fs.existsSync(gpmoRoot)) {
    console.warn('[generate-gpmo-manifest] GPMO/ not found; writing empty tree.');
    fs.mkdirSync(path.dirname(outFile), {recursive: true});
    fs.writeFileSync(
      outFile,
      `// Auto-generated — run: npm run generate:gpmo
export type GpmoFileNode = { type: 'file'; name: string; relPath: string };
export type GpmoDirNode = { type: 'dir'; name: string; children: GpmoNode[] };
export type GpmoNode = GpmoFileNode | GpmoDirNode;
export type GpmoDocumentTree = { children: GpmoNode[] };
export const gpmoDocumentTree: GpmoDocumentTree = { children: [] };
`,
      'utf8',
    );
    return;
  }

  const children = walkDir(gpmoRoot, '');
  const json = JSON.stringify({children}, null, 2);

  fs.mkdirSync(path.dirname(outFile), {recursive: true});
  const ts = `// Auto-generated by scripts/generate-gpmo-manifest.mjs — run: npm run generate:gpmo

export type GpmoFileNode = { type: 'file'; name: string; relPath: string };
export type GpmoDirNode = { type: 'dir'; name: string; children: GpmoNode[] };
export type GpmoNode = GpmoFileNode | GpmoDirNode;
export type GpmoDocumentTree = { children: GpmoNode[] };

export const gpmoDocumentTree: GpmoDocumentTree = ${json};
`;

  fs.writeFileSync(outFile, ts, 'utf8');
  console.log(`[generate-gpmo-manifest] Wrote ${outFile} (${children.length} top-level entries).`);
}

main();
