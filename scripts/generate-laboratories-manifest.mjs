/**
 * Walks `Laboratories/` and emits `src/generated/laboratoriesManifest.ts`.
 * Run: node scripts/generate-laboratories-manifest.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const laboratoriesRoot = path.join(projectRoot, 'Laboratories');
const outFile = path.join(projectRoot, 'src', 'generated', 'laboratoriesManifest.ts');

function walkDir(dirPath, relPrefix) {
  let entries = [];
  try {
    entries = fs.readdirSync(dirPath, {withFileTypes: true});
  } catch {
    return [];
  }
  entries.sort((a, b) => {
    if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
    return a.name.localeCompare(b.name);
  });

  const children = [];
  for (const ent of entries) {
    if (ent.name.startsWith('.')) continue;
    const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name;
    const full = path.join(dirPath, ent.name);
    if (ent.isDirectory()) {
      children.push({
        type: 'dir',
        name: ent.name,
        children: walkDir(full, rel),
      });
    } else {
      children.push({
        type: 'file',
        name: ent.name,
        relPath: rel.replace(/\\/g, '/'),
      });
    }
  }
  return children;
}

function main() {
  if (!fs.existsSync(laboratoriesRoot)) {
    console.warn('[generate-laboratories-manifest] Laboratories/ not found; writing empty tree.');
    fs.mkdirSync(path.dirname(outFile), {recursive: true});
    fs.writeFileSync(
      outFile,
      `// Auto-generated — run: npm run generate:laboratories
export type LaboratoryFileNode = { type: 'file'; name: string; relPath: string };
export type LaboratoryDirNode = { type: 'dir'; name: string; children: LaboratoryNode[] };
export type LaboratoryNode = LaboratoryFileNode | LaboratoryDirNode;
export type LaboratoriesDocumentTree = { children: LaboratoryNode[] };
export const laboratoriesDocumentTree: LaboratoriesDocumentTree = { children: [] };
`,
      'utf8',
    );
    return;
  }

  const children = walkDir(laboratoriesRoot, '');
  const json = JSON.stringify({children}, null, 2);

  fs.mkdirSync(path.dirname(outFile), {recursive: true});
  const ts = `// Auto-generated by scripts/generate-laboratories-manifest.mjs — run: npm run generate:laboratories

export type LaboratoryFileNode = { type: 'file'; name: string; relPath: string };
export type LaboratoryDirNode = { type: 'dir'; name: string; children: LaboratoryNode[] };
export type LaboratoryNode = LaboratoryFileNode | LaboratoryDirNode;
export type LaboratoriesDocumentTree = { children: LaboratoryNode[] };

export const laboratoriesDocumentTree: LaboratoriesDocumentTree = ${json};
`;

  fs.writeFileSync(outFile, ts, 'utf8');
  console.log(`[generate-laboratories-manifest] Wrote ${outFile} (${children.length} top-level entries).`);
}

main();
